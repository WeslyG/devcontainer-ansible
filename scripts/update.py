"""Discover stable releases and resolve fresh compatible locks in each controller Python."""
import argparse
import concurrent.futures
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import tempfile
from common import ROOT, fetch, matrix, run, write_json, cli, config
from render import render

FAMILIES={'10':('3.12','2.17'),'12':('3.13','2.19'),'14':('3.14','2.21')}

def release(repo):
    return fetch(f'https://api.github.com/repos/{repo}/releases/latest')['tag_name'].removeprefix('v')

def discover(data):
    builder=fetch('https://hub.docker.com/v2/repositories/library/debian/tags/trixie-slim')
    data['gitBuilderImage']='debian:trixie-slim@'+builder['digest']
    for major,(python,core) in FAMILIES.items():
        tags=fetch(f'https://hub.docker.com/v2/repositories/library/python/tags?page_size=100&name={python}.')['results']
        tags=[t for t in tags if re.fullmatch(re.escape(python)+r'\.\d+-slim-trixie',t['name'])]
        tag=max(tags,key=lambda t:tuple(map(int,t['name'].split('-')[0].split('.'))))
        data['variants'][major]['pythonImage']=f"python:{tag['name']}@{tag['digest']}"
    nodes=[n for n in fetch('https://nodejs.org/dist/index.json') if re.fullmatch(r'v\d+\.\d+\.\d+',n['version'])]
    node=max(nodes,key=lambda n:tuple(map(int,n['version'][1:].split('.'))))['version'][1:]
    checks=fetch(f'https://nodejs.org/dist/v{node}/SHASUMS256.txt',False)
    sha=lambda arch:re.search(r'^([a-f0-9]{64})\s+node-v'+re.escape(node)+'-linux-'+arch+r'\.tar\.xz$',checks,re.M)[1]
    data['tools']['node']={'version':node,'sha256Amd64':sha('x64'),'sha256Arm64':sha('arm64')}
    for key,repo in [('gilt','retr0h/gilt'),('k9s','derailed/k9s')]:data['tools'][key]=release(repo)
    data['tools']['kubernetes']={'version':fetch('https://dl.k8s.io/release/stable.txt',False).strip().removeprefix('v'),'helm':release('helm/helm'),'minikube':release('kubernetes/minikube')}
    npm=lambda name:fetch('https://registry.npmjs.org/'+name)['dist-tags']['latest']
    data['tools']['node']['npmVersion']=npm('npm')
    data['tools']['cliTools']={'claudeVersion':npm('@anthropic-ai/claude-code'),'elasticdumpVersion':npm('elasticdump')}
    for arch,package in [('Amd64','x64'),('Arm64','arm64')]:
        native=fetch('https://registry.npmjs.org/@anthropic-ai/claude-code-linux-'+package+'/'+data['tools']['cliTools']['claudeVersion'])
        data['tools']['cliTools']['claudeIntegrity'+arch]=native['dist']['integrity']
    data['devcontainerCli']=npm('@devcontainers/cli')
    kernel=fetch('https://www.kernel.org/pub/software/scm/git/',False)
    versions=re.findall(r'git-(2\.\d+\.\d+)\.tar\.xz',kernel)
    git=max(versions,key=lambda v:tuple(map(int,v.split('.'))))
    sums=fetch('https://www.kernel.org/pub/software/scm/git/sha256sums.asc',False)
    digest=re.search(r'^([a-f0-9]{64})\s+git-'+re.escape(git)+r'\.tar\.xz$',sums,re.M)[1]
    data['tools']['git']={'version':git,'sha256':digest}
    data['actions']={repo:fetch('https://api.github.com/repos/'+repo+'/releases/latest')['tag_name'] for repo in ['actions/checkout','actions/setup-node','actions/upload-artifact','docker/setup-buildx-action']}
    data['updatedAt']=datetime.now(timezone.utc).date().isoformat()
    return data

def lock(major,data):
    folder=ROOT/'.build';folder.mkdir(exist_ok=True)
    report=folder/f'resolve-{major}.json'
    run(['docker','run','--rm','--user',f'{__import__("os").getuid()}:{__import__("os").getgid()}',
         '-e','PIP_NO_CACHE_DIR=1','-e','PIP_DISABLE_PIP_VERSION_CHECK=1','-v',f'{ROOT}:/repo',
         data['variants'][major]['pythonImage'],'python','-m','pip','install','--dry-run','--ignore-installed',
         '--report',f'/repo/.build/{report.name}','-r','/repo/requirements/common.in','-r',f'/repo/requirements/ansible{major}.in'])
    selected=json.loads(report.read_text())['install']
    def hashes(item):
        meta=item['metadata'];name=meta['name'];version=meta['version']
        urls=fetch(f'https://pypi.org/pypi/{name}/{version}/json')['urls']
        hs=sorted({f['digests']['sha256'] for f in urls if not f.get('yanked')})
        if not hs:raise RuntimeError(f'No release hashes for {name} {version}')
        return name.lower().replace('_','-'),version,hs
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:rows=sorted(pool.map(hashes,selected))
    text='# Generated by scripts/update.py --write --resolve. Do not edit by hand.\n'
    text+='# All non-yanked PyPI artifact hashes allow amd64 and arm64 installs.\n'
    for name,version,hs in rows:
        text+=f'{name}=={version} \\\n'+' \\\n'.join('    --hash=sha256:'+h for h in hs)+'\n'
    return {n:v for n,v,_ in rows},text

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--write',action='store_true',help='Apply discovered versions; without this flag only write an audit report.')
    parser.add_argument('--resolve',action='store_true',help='Resolve fresh hash-locked Python requirements for all variants.')
    parser.add_argument('--features',action='store_true',help='Refresh each external feature lock using devcontainer upgrade.')
    args=parser.parse_args()
    data=discover(matrix())
    write_json(ROOT/'.build/latest-releases.json',data)
    if not args.write:
        print('Audit written to .build/latest-releases.json; working configuration unchanged.');return
    selected={};locks={}
    if args.resolve:
        # Do not replace any Python lock until all three resolvers have succeeded.
        for major in data['variants']:selected[major],locks[major]=lock(major,data)
        for major,text in locks.items():(ROOT/f'requirements/ansible{major}.txt').write_text(text)
        write_json(ROOT/'compatibility/resolved.json',{'updatedAt':data['updatedAt'],'packages':selected})
    write_json(ROOT/'images.json',data);render()
    if args.features:
        for major in data['variants']:run([cli(),'upgrade','--workspace-folder',ROOT,'--config',config(major)])
        (ROOT/'.devcontainer/devcontainer-lock.json').write_bytes((config(data['default']).parent/'devcontainer-lock.json').read_bytes())

if __name__=='__main__':main()
